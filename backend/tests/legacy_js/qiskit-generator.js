function generateQiskit(ir, doc) {
  const n = ir.n;


  const labelToIdx = {};
  ir.qubits.forEach((q, i) => { labelToIdx[q.label] = i; });

  const lines   = [];
  const remarks = [];

  const emit = (code, remark='') => { lines.push(code); remarks.push(remark); };
  const blank = (remark='') => emit('', remark);


  emit('from qiskit import QuantumCircuit, transpile');
  emit('from qiskit_aer import AerSimulator');
  blank();
  emit(`# Generated by QuantumCanvas  —  ${doc.title}`);
  emit(`# Pattern: ${ir.validation.pattern}`);
  blank();


  emit(`qc = QuantumCircuit(${n}, ${n})`,
       `${n} qubit${n>1?'s':''}, ${n} classical bit${n>1?'s':''} for measurement`);
  blank();


  function _emitMCZ(idxs, emitFn) {


    const m = idxs.length;
    if(m === 0) return;
    if(m === 1) {
      emitFn(`qc.z(${idxs[0]})`, 'Z = phase flip on |1⟩');
      return;
    }
    const target   = idxs[m-1];
    const controls = idxs.slice(0, m-1);

    emitFn(`qc.h(${target})`, 'MCZ via H·MCX·H');
    if(m === 2) {
      emitFn(`qc.cx(${controls[0]}, ${target})`, 'CX (2-qubit case)');
    } else if(m === 3) {
      emitFn(`qc.ccx(${controls[0]}, ${controls[1]}, ${target})`, 'CCX (3-qubit case)');
    } else {

      emitFn(`qc.mcx([${controls.join(', ')}], ${target})`,
             `multi-controlled X on ${m} qubits`);
    }
    emitFn(`qc.h(${target})`);
  }


  let hasUnimplemented = false;

  doc.steps.forEach(step => {
    switch(step.op) {

      case 'INITIALIZE':
        emit('# INITIALIZE — all qubits start in |0⟩ (Qiskit default, no gates needed)');
        blank();
        break;

      case 'SHAKE': {
        emit(`# SHAKE ${step.targets.join(', ')} — Hadamard: equal superposition`);
        step.targets.forEach(lbl => {
          const idx = labelToIdx[lbl];
          if(idx === undefined) return;
          emit(`qc.h(${idx})`,
               `${lbl} → |+⟩ = (|0⟩+|1⟩)/√2`);
        });
        blank();
        break;
      }

      case 'MARK': {


        const markedIdxs  = step.targets.map(lbl => labelToIdx[lbl]).filter(i => i !== undefined);
        const allIdxs     = ir.qubits.map((_,i) => i);
        const unmarkedIdxs = allIdxs.filter(i => !markedIdxs.includes(i));

        emit(`# MARK ${step.targets.join(', ')} — computational basis oracle`);
        emit(`# Marks the |${'1'.repeat(markedIdxs.length)}⟩ state of [${step.targets.join(', ')}]`);
        emit(`# using X·MCZ·X pattern (phase -1 on target basis state only)`);

        if(markedIdxs.length === 1 && n === 1) {

          emit(`qc.z(${markedIdxs[0]})`,
               `${step.targets[0]}: phase -1 on |1⟩ state`);
        } else if(markedIdxs.length === 1) {


          unmarkedIdxs.forEach(i => emit(`qc.x(${i})`, `flip to align with target basis state`));

          _emitMCZ(allIdxs, emit);

          unmarkedIdxs.forEach(i => emit(`qc.x(${i})`, `restore`));
        } else {

          unmarkedIdxs.forEach(i => emit(`qc.x(${i})`, `flip unmarked qubit`));
          _emitMCZ(allIdxs, emit);
          unmarkedIdxs.forEach(i => emit(`qc.x(${i})`, `restore`));
        }
        blank();
        break;
      }

      case 'BOOST': {


        const allIdxs   = ir.qubits.map((_,i) => i);
        const allLabels = ir.qubits.map(q => q.label).join(', ');

        emit(`# BOOST — Grover diffusion: 2|ψ⟩⟨ψ| - I on [${allLabels}]`);
        emit(`# Step 1: H on all — rotate to computational basis`);
        allIdxs.forEach(i => emit(`qc.h(${i})`));
        blank('');
        emit(`# Step 2: X on all — shift |0...0⟩ to |1...1⟩`);
        allIdxs.forEach(i => emit(`qc.x(${i})`));
        blank('');
        emit(`# Step 3: multi-controlled phase flip on |1...1⟩`);
        _emitMCZ(allIdxs, emit);
        blank('');
        emit(`# Step 4: X on all — undo shift`);
        allIdxs.forEach(i => emit(`qc.x(${i})`));
        blank('');
        emit(`# Step 5: H on all — rotate back`);
        allIdxs.forEach(i => emit(`qc.h(${i})`));
        blank();
        break;
      }

      case 'LINK': {

        const [ctrlLbl, tgtLbl] = step.targets;
        const ctrlIdx = labelToIdx[ctrlLbl];
        const tgtIdx  = labelToIdx[tgtLbl];
        if(ctrlIdx === undefined || tgtIdx === undefined) break;
        emit(`# ENTANGLE ${ctrlLbl} → ${tgtLbl} — CNOT: entangle pair`);
        emit(`qc.cx(${ctrlIdx}, ${tgtIdx})`,
             `control=${ctrlLbl}(q${ctrlIdx}), target=${tgtLbl}(q${tgtIdx}) → Bell pair |Φ+⟩`);
        blank();
        break;
      }

      case 'LOOK': {
        const tag = step.code.includes('correlated') ? ' (correlated)' : '';
        emit(`# MEASURE ${step.targets.join(', ')}${tag} — measure into classical bits`);
        step.targets.forEach(lbl => {
          const idx = labelToIdx[lbl];
          if(idx === undefined) return;
          emit(`qc.measure(${idx}, ${idx})`,
               `${lbl} → classical bit ${idx}`);
        });
        blank();
        break;
      }

      default:
        break;
    }
  });


  emit('# ── Run on Aer simulator ──────────────────────────────────────');
  emit('simulator = AerSimulator()');
  emit('compiled  = transpile(qc, simulator)');
  emit('job       = simulator.run(compiled, shots=1000)');
  emit('result    = job.result()');
  emit('counts    = result.get_counts()');
  blank();
  emit('print("Circuit:")', 'print the circuit diagram');
  emit('print(qc.draw(output="text"))');
  blank();
  emit('print("\\nMeasurement counts (1000 shots):")');
  emit('for state, count in sorted(counts.items(), key=lambda x: -x[1]):');
  emit('    print(f"  |{state}⟩: {count} ({count/10:.1f}%)")');

  return { lines, remarks, hasUnimplemented, n, labelToIdx };
}
